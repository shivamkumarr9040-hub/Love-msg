import { chromium } from 'playwright-core';
const errors = [];
const browser = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1255/chrome-linux64/chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', e => errors.push(String(e)));
page.on('requestfailed', r => errors.push('req-failed: ' + r.url()));
await page.goto('http://localhost:8001/', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(1500);
const visible = async (sel) => page.evaluate((sel) => {
  const el = document.querySelector(sel);
  if (!el) return 'missing';
  const cs = getComputedStyle(el);
  return cs.display !== 'none' && cs.visibility !== 'hidden' && el.getBoundingClientRect().height > 0;
}, sel);
console.log('phone visible:', await visible('.phone'));
console.log('login heading:', (await page.textContent('.phone-body h2'))?.trim());
console.log('no dashboard in page:', await page.evaluate(() => !document.getElementById('dashStage')));
console.log('setup hint shown:', await page.evaluate(() => !document.getElementById('loginSetupHint').hidden));
console.log('has google btn:', (await page.textContent('#googleBtn'))?.includes('Google'));
console.log('has signup btn:', (await page.textContent('#signupBtn'))?.includes('Create a new account'));
await page.fill('#loginEmail', 'test@example.com');
await page.fill('#loginPassword', 'password123');
await page.click('#loginBtn');
await page.waitForTimeout(500);
console.log('signin error shown:', (await page.textContent('#loginError'))?.includes('Supabase setup pending'));
console.log('signin btn re-enabled:', await page.evaluate(() => !document.getElementById('loginBtn').disabled));
await page.click('#googleBtn');
await page.waitForTimeout(500);
console.log('google error shown:', (await page.textContent('#loginError'))?.includes('Supabase setup pending'));
await page.click('#signupBtn');
await page.waitForTimeout(500);
console.log('signup error shown:', (await page.textContent('#loginError'))?.includes('Supabase setup pending'));
// Simulate signed-in state (CSS/JS gate only) — proves success view works
await page.evaluate(() => {
  document.querySelector('.phone-body').classList.add('signed-in');
  document.getElementById('loginSuccess').hidden = false;
  document.getElementById('successEmail').textContent = 'test@example.com';
});
await page.waitForTimeout(400);
console.log('success visible:', await visible('#loginSuccess'));
console.log('success text:', (await page.textContent('#loginSuccess'))?.includes('signed in'));
await page.click('#logoutBtn');
await page.waitForTimeout(400);
console.log('after logout: login form back:', await visible('#loginEmail'));
console.log('after logout: success hidden:', await page.evaluate(() => document.getElementById('loginSuccess').hidden));
console.log('CONSOLE ERRORS:', errors.length, errors);
await browser.close();
if (errors.length) process.exit(1);
